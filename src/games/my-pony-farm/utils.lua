local Utils = require("../../utils")

local M = {}

M.getDropsFolder = function()
	return workspace:FindFirstChild("Drops")
end

M.getDrops = function()
	local dropsFolder = M.getDropsFolder()

	if not dropsFolder then
		return {}
	end

	return dropsFolder:GetChildren()
end

local function split(str, sep)
	sep = sep or "%s"
	local result = {}
	for match in string.gmatch(str, "([^" .. sep .. "]+)") do
		table.insert(result, match)
	end
	return result
end

local function touch(part)
	local root = Utils.getLocalRoot()

	if part and root then
		firetouchinterest(part, root, true)
		firetouchinterest(part, root, false)
	end
end

M.grabDrop = function(drop)
	local t = drop:FindFirstChild("Touch")

	touch(t)
end

M.grabAllDrops = function()
	local drops = M.getDrops()

	for _, drop in pairs(drops) do
		M.grabDrop(drop)
	end
end

M.tycoon = nil

M.getTycoon = function()
	if M.tycoon then
		return M.tycoon
	end

	local remotes = game:GetService("ReplicatedStorage"):FindFirstChild("Remotes")
	local gohome = remotes and remotes:FindFirstChild("GoHome")

	if not gohome then
		return nil
	end

	gohome:FireServer()

	task.wait(1)

	local tycoon = workspace:FindFirstChild("Tycoon")
	local tycoonsModel = tycoon and tycoon:FindFirstChild("Tycoons")
	local tycoons = tycoonsModel and tycoonsModel:GetChildren()

	local best = nil
	local best_dist = 99999999

	local root = Utils.getLocalRoot()

	for i, v in pairs(tycoons) do
		local spawner = v:FindFirstChild("Spawner")
		if spawner then
			local dist = Utils.dist3d(spawner.Position, root.Position)

			if dist < best_dist then
				best_dist = dist
				best = v
			end
		end
	end

	if not best then
		return nil
	end

	M.tycoon = best
end

M.getTycoonEssentials = function()
	local tycoon = M.getTycoon()
	local essentials = tycoon and tycoon:FindFirstChild("Essentials")

	return essentials
end

M.getMultText = function()
	local essentials = M.getTycoonEssentials()
	local shop = essentials and essentials:FindFirstChild("Shop")
	local marketDisplay = shop and shop:FindFirstChild("MarketDisplay")
	local surfaceGui = marketDisplay and marketDisplay:FindFirstChild("SurfaceGui")
	local frame = surfaceGui and surfaceGui:FindFirstChild("Frame")
	local multipleFrame = frame and frame:FindFirstChild("MultipleFrame")
	local multipleText = multipleFrame and multipleFrame:FindFirstChild("MultipleText")

	if multipleText then
		return multipleText.Text
	end

	return "0.00x"
end

M.getMult = function()
	local multText = M.getMultText()
	local multStr = split(multText, "x")[1]
	local mult = tonumber(multStr)

	return mult
end

M.getTycoonButtons = function()
	local tycoon = M.getTycoon()
	local buttons = tycoon and tycoon:FindFirstChild("Buttons")

	return buttons
end

M.touchButton = function(button)
	local head = button and button:FindFirstChild("Head")
	touch(head)
end

M.getTycoonDepositButton = function()
	local buttons = M.getTycoonButtons()
	local depositButton = buttons and buttons:FindFirstChild("Deposit")

	return depositButton
end

M.touchDepositButton = function()
	local depositButton = M.getTycoonDepositButton()
	M.touchButton(depositButton)
end

